// Helper functions for search, filter & lookup
export function getTemplateById(id: string): MenuTemplate {
  return ALL_TEMPLATES.find(t => t.id === id) || ALL_TEMPLATES[0];
}

export function getTemplateByCode(code: string): MenuTemplate {
  return ALL_TEMPLATES.find(t => t.code === code) || ALL_TEMPLATES[0];
}

export function searchTemplates(
  query: string = '',
  category: string = 'All',
  layout?: LayoutModel
): MenuTemplate[] {
  const cleanQ = query.trim().toLowerCase();

  return ALL_TEMPLATES.filter(tpl => {
    const matchesCategory = category === 'All' || tpl.category === category;
    const matchesLayout = !layout || tpl.layoutModel === layout;

    if (!cleanQ) {
      return matchesCategory && matchesLayout;
    }

    const matchesName = tpl.name.toLowerCase().includes(cleanQ);
    const matchesVibe = tpl.vibe.toLowerCase().includes(cleanQ);
    const matchesDesc = tpl.description.toLowerCase().includes(cleanQ);
    const matchesTags = tpl.tags.some(t => t.toLowerCase().includes(cleanQ));
    const matchesFont = tpl.fontHeading.toLowerCase().includes(cleanQ) || tpl.fontBody.toLowerCase().includes(cleanQ);

    return matchesCategory && matchesLayout && (matchesName || matchesVibe || matchesDesc || matchesTags || matchesFont);
  });
}
